"""Financial-strength checklist — the Piotroski F-score method, computed from reported annual data.

Nine yes/no tests comparing the latest fiscal year with the one before (Piotroski, 2000,
"Value Investing: The Use of Historical Financial Statement Information"). Each passed test
scores 1. This is a fixed rule set, not a prediction, rating or recommendation, and not AI.

A test whose inputs the filer does not report is marked "not available" and left out of the
denominator, so a score is always shown as "passed / available". Growth-type tests require the
two fiscal years to be consecutive.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass

import pandas as pd

from fip.formatting import format_percent, is_missing


@dataclass
class Check:
    key: str
    group: str        # Profitability | Balance sheet & funding | Efficiency
    question: str     # plain-English question the test answers
    passed: bool | None   # None = not available
    detail: str       # what the numbers were, in words
    why: str          # why it matters, one sentence

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class HealthScore:
    fiscal_year: int | None
    prior_year: int | None
    checks: list
    passed: int
    available: int
    verdict: str      # Strong | Average | Weak | Not enough data
    summary: str

    def to_dict(self) -> dict:
        d = asdict(self)
        d["checks"] = [c.to_dict() if hasattr(c, "to_dict") else c for c in self.checks]
        return d


def _num(row, key):
    if row is None:
        return None
    v = row.get(key) if hasattr(row, "get") else None
    return None if is_missing(v) else float(v)


def _ratio(a, b):
    return None if a is None or b is None or b == 0 else a / b


def _pct(x):
    return format_percent(x, decimals=1)


def health_score(df: pd.DataFrame) -> HealthScore:
    if df is None or df.empty:
        return HealthScore(None, None, [], 0, 0, "Not enough data", "No annual figures are available.")
    last = df.iloc[-1]
    prev = df.iloc[-2] if len(df) > 1 and bool(df.iloc[-1].get("consecutive", False)) else None
    fy = int(last["fiscal_year"])
    pfy = int(prev["fiscal_year"]) if prev is not None else None
    a = lambda k: _num(last, k)  # noqa: E731
    b = lambda k: _num(prev, k)  # noqa: E731

    roa, roa_prev = _ratio(a("net_income"), a("total_assets")), _ratio(b("net_income"), b("total_assets"))
    cfo = a("operating_cash_flow")
    lev, lev_prev = _ratio(a("long_term_debt"), a("total_assets")), _ratio(b("long_term_debt"), b("total_assets"))
    cr, cr_prev = _ratio(a("current_assets"), a("current_liabilities")), _ratio(b("current_assets"), b("current_liabilities"))
    gm, gm_prev = _ratio(a("gross_profit"), a("revenue")), _ratio(b("gross_profit"), b("revenue"))
    at, at_prev = _ratio(a("revenue"), a("total_assets")), _ratio(b("revenue"), b("total_assets"))
    sh, sh_prev = a("shares_diluted"), b("shares_diluted")

    def check(key, group, question, value_ok, detail, why):
        return Check(key, group, question, value_ok, detail, why)

    na = "Not reported in the filing data, so this test is skipped."
    need_prev = f"Needs the previous consecutive fiscal year, which isn't available."
    checks = [
        check("profitable", "Profitability", "Did the company make a profit?",
              None if roa is None else roa > 0,
              na if roa is None else f"Net income was {_pct(roa)} of total assets in FY{fy}.",
              "Profitable companies can fund themselves without borrowing or issuing shares."),
        check("cash_positive", "Profitability", "Did the business bring in cash from operations?",
              None if cfo is None else cfo > 0,
              na if cfo is None else ("Operating cash flow was positive." if cfo > 0 else "Operating cash flow was negative."),
              "Cash generated by the core business is harder to dress up than accounting profit."),
        check("roa_up", "Profitability", "Is profitability improving?",
              None if roa is None or roa_prev is None else roa > roa_prev,
              (need_prev if prev is None else na) if roa is None or roa_prev is None
              else f"Return on assets went from {_pct(roa_prev)} (FY{pfy}) to {_pct(roa)} (FY{fy}).",
              "Rising returns suggest the business is getting stronger, not just bigger."),
        check("quality", "Profitability", "Are profits backed by real cash?",
              None if cfo is None or a("net_income") is None else cfo > a("net_income"),
              na if cfo is None or a("net_income") is None
              else ("Operating cash flow was higher than net income." if cfo > a("net_income")
                    else "Operating cash flow was lower than net income."),
              "When cash lags profit, earnings may rely on accounting estimates."),
        check("debt_down", "Balance sheet & funding", "Is long-term debt shrinking relative to assets?",
              None if lev is None or lev_prev is None else lev <= lev_prev,
              (need_prev if prev is None else na) if lev is None or lev_prev is None
              else f"Long-term debt was {_pct(lev_prev)} of assets in FY{pfy} and {_pct(lev)} in FY{fy}.",
              "Less leverage means less pressure from interest payments and lenders."),
        check("liquidity_up", "Balance sheet & funding", "Can it pay short-term bills more easily than last year?",
              None if cr is None or cr_prev is None else cr > cr_prev,
              (need_prev if prev is None else na) if cr is None or cr_prev is None
              else f"Current assets covered current liabilities {cr_prev:.2f}× in FY{pfy} and {cr:.2f}× in FY{fy}.",
              "A higher ratio means more short-term resources for each dollar due within a year."),
        check("no_dilution", "Balance sheet & funding", "Did it avoid issuing more shares?",
              None if sh is None or sh_prev is None else sh <= sh_prev * 1.005,
              (need_prev if prev is None else na) if sh is None or sh_prev is None
              else f"Diluted share count went from {sh_prev / 1e6:,.1f}M to {sh / 1e6:,.1f}M.",
              "New shares dilute existing owners; mature, healthy firms rarely need them."),
        check("margin_up", "Efficiency", "Is the gross margin improving?",
              None if gm is None or gm_prev is None else gm > gm_prev,
              (need_prev if prev is None else na) if gm is None or gm_prev is None
              else f"Gross margin went from {_pct(gm_prev)} to {_pct(gm)}.",
              "Better margins point to pricing power or lower costs."),
        check("turnover_up", "Efficiency", "Is it producing more sales from its assets?",
              None if at is None or at_prev is None else at > at_prev,
              (need_prev if prev is None else na) if at is None or at_prev is None
              else f"Revenue per dollar of assets went from {at_prev:.2f} to {at:.2f}.",
              "Higher asset turnover means the company uses what it owns more productively."),
    ]
    available = sum(c.passed is not None for c in checks)
    passed = sum(c.passed is True for c in checks)
    if available < 5:
        verdict = "Not enough data"
        summary = (f"Only {available} of 9 tests could be run from the reported figures, so no overall reading is "
                   "given. Banks and insurers often don't report the balance-sheet items these tests need.")
    else:
        share = passed / available
        verdict = "Strong" if share >= 7 / 9 else "Weak" if share <= 3 / 9 else "Average"
        summary = f"Passed {passed} of {available} tests for FY{fy}" + (f" compared with FY{pfy}." if pfy else ".")
    return HealthScore(fy, pfy, checks, passed, available, verdict, summary)
